document.querySelector("#coffee-checkout-form")?.addEventListener("submit", async (event) => {
    event.preventDefault();
    const submitButton = document.querySelector("#coffee-checkout-submit");
    const errorMessage = document.querySelector("#coffee-checkout-error");
    const copy = translations[languageSelect?.value || "en"] || translations.en;
    const preset = currencyPresets[currentCoffeeCurrency] || currencyPresets.USD;
    const amount = selectedCoffeeAmount;

    if (!Number.isInteger(amount) || amount < preset.min || amount > preset.max) {
        errorMessage.textContent = copy.coffeeCheckoutError;
        errorMessage.hidden = false;
        return;
    }
    submitButton.disabled = true;
    errorMessage.hidden = true;
    try {
        const response = await fetch("/api/payments/paytr/create", {
            method: "POST",
            headers: { "content-type": "application/json" },
            body: JSON.stringify({
                amount,
                currency: currentCoffeeCurrency,
                email: event.currentTarget.elements.email.value.trim(),
                lang: languageSelect?.value || "en"
            })
        });
        const result = await response.json().catch(() => ({}));
        if (!response.ok || !result.iframeUrl) throw new Error(result.error || copy.coffeeCheckoutError);
        const checkoutUrl = new URL(result.iframeUrl);
        if (checkoutUrl.origin !== "https://www.paytr.com") throw new Error(copy.coffeeCheckoutError);
        document.querySelector("#paytr-frame").src = checkoutUrl.href;
        document.querySelector("#paytr-frame-wrap").hidden = false;
        submitButton.hidden = true;
    } catch (error) {
        errorMessage.textContent = error.message && !error.message.includes("Unexpected token") && !error.message.includes("Forbidden") ? error.message : copy.coffeeCheckoutError;
        errorMessage.hidden = false;
    } finally {
        submitButton.disabled = false;
    }
});
