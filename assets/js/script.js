function drawChart(progress = 1) {
    if (!chartCanvas || !chartContext) return;
    const bounds = chartCanvas.getBoundingClientRect();
    const pixelRatio = window.devicePixelRatio || 1;
    if (!bounds.width || !bounds.height) return;

    chartCanvas.width = Math.round(bounds.width * pixelRatio);
    chartCanvas.height = Math.round(bounds.height * pixelRatio);
    chartContext.setTransform(pixelRatio, 0, 0, pixelRatio, 0, 0);

    const width = bounds.width;
    const height = bounds.height;
    const values = chartData[currentPeriod];
    const padding = { top: 7, right: 4, bottom: 8, left: 4 };
    const plotWidth = width - padding.left - padding.right;
    const plotHeight = height - padding.top - padding.bottom;
    const points = values.map((value, index) => ({
        x: padding.left + (index / (values.length - 1)) * plotWidth,
        y: padding.top + plotHeight - (value / 100) * plotHeight
    }));
    const visibleCount = Math.max(2, Math.ceil(points.length * progress));
    const visiblePoints = points.slice(0, visibleCount);

    chartContext.clearRect(0, 0, width, height);
    chartContext.lineWidth = 1;
    chartContext.setLineDash([3, 4]);
    chartContext.strokeStyle = "#edf0eb";
    for (let line = 0; line < 4; line += 1) {
        const y = padding.top + (plotHeight / 3) * line;
        chartContext.beginPath();
        chartContext.moveTo(0, y);
        chartContext.lineTo(width, y);
        chartContext.stroke();
    }
    chartContext.setLineDash([]);

    function traceLine() {
        chartContext.beginPath();
        visiblePoints.forEach((point, index) => {
            if (index === 0) chartContext.moveTo(point.x, point.y);
            else {
                const previous = visiblePoints[index - 1];
                const midpoint = (previous.x + point.x) / 2;
                chartContext.bezierCurveTo(midpoint, previous.y, midpoint, point.y, point.x, point.y);
            }
        });
    }

    if (visiblePoints.length > 1) {
        traceLine();
        const gradient = chartContext.createLinearGradient(0, padding.top, 0, height);
        gradient.addColorStop(0, "rgba(128, 169, 91, .21)");
        gradient.addColorStop(1, "rgba(128, 169, 91, 0)");
        chartContext.lineTo(visiblePoints.at(-1).x, height);
        chartContext.lineTo(visiblePoints[0].x, height);
        chartContext.closePath();
        chartContext.fillStyle = gradient;
        chartContext.fill();
    }

    traceLine();
    chartContext.strokeStyle = "#6e995c";
    chartContext.lineWidth = 2;
    chartContext.lineCap = "round";
    chartContext.lineJoin = "round";
    chartContext.stroke();

    const lastPoint = visiblePoints.at(-1);
    chartContext.beginPath();
    chartContext.arc(lastPoint.x, lastPoint.y, 3.2, 0, Math.PI * 2);
    chartContext.fillStyle = "#ffffff";
    chartContext.fill();
    chartContext.lineWidth = 2;
    chartContext.strokeStyle = "#6e995c";
    chartContext.stroke();
}

function animateChart(timestamp) {
    if (!chartStartTime) chartStartTime = timestamp;
    chartProgress = Math.min((timestamp - chartStartTime) / 1050, 1);
    drawChart(chartProgress);
    if (chartProgress < 1) chartAnimationId = requestAnimationFrame(animateChart);
}

function startChartAnimation() {
    if (!chartCanvas) return;
    cancelAnimationFrame(chartAnimationId);
    chartStartTime = 0;
    chartProgress = reduceMotion ? 1 : 0;
    if (reduceMotion) drawChart(1);
    else chartAnimationId = requestAnimationFrame(animateChart);
}

