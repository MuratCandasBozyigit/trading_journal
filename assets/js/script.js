function formatCoffeeAmount(amount, currency) {
    const config = currencyPresets[currency] || currencyPresets.USD;
    return config.symbolPosition === "before" ? `${config.symbol}${amount}` : `${amount} ${config.symbol}`;
}

function selectCoffeeCurrency(currency) {
    if (!currencyPresets[currency]) return;
    currentCoffeeCurrency = currency;
    selectedCoffeeAmount = currencyPresets[currency].defaultAmount;
    document.querySelectorAll("#custom-coffee-amount").forEach((input) => { input.value = ""; });
    renderCoffeeSection();
}

function renderCoffeeSection() {
    const lang = languageSelect?.value || "en";
    const copy = translations[lang] || translations.en;
    const preset = currencyPresets[currentCoffeeCurrency] || currencyPresets.USD;

    document.querySelectorAll(".coffee-currency-picker button").forEach((button) => {
        button.setAttribute("aria-pressed", String(button.dataset.currency === currentCoffeeCurrency));
    });

    document.querySelectorAll(".coffee-amounts-grid, #coffee-amounts").forEach((container) => {
        container.replaceChildren();
        preset.amounts.forEach((amount) => {
            const btn = document.createElement("button");
            btn.type = "button";
            btn.className = "coffee-amount-btn";
            btn.dataset.coffeeAmount = String(amount);
            btn.setAttribute("aria-pressed", String(amount === selectedCoffeeAmount));

            const val = document.createElement("span");
            val.className = "coffee-amount-val";
            val.textContent = formatCoffeeAmount(amount, currentCoffeeCurrency);

            const perk = document.createElement("span");
            perk.className = "coffee-amount-perk";
            perk.textContent = copy[`coffeePerk_${amount}`] || "";

            btn.append(val, perk);
            btn.addEventListener("click", () => {
                selectedCoffeeAmount = amount;
                document.querySelectorAll("#custom-coffee-amount").forEach((input) => { input.value = ""; });
                renderCoffeeSection();
            });
            container.append(btn);
        });
    });

    document.querySelectorAll(".custom-amount-symbol").forEach((el) => {
        el.textContent = preset.symbol;
    });

    document.querySelectorAll("#custom-coffee-amount").forEach((input) => {
        input.min = String(preset.min);
        input.max = String(preset.max);
        input.placeholder = String(preset.defaultPlaceholder);
    });

    document.querySelectorAll("#coffee-btn-label, .coffee-btn-text").forEach((el) => {
        el.textContent = `${copy.coffeeSupportCta} (${formatCoffeeAmount(selectedCoffeeAmount, currentCoffeeCurrency)})`;
    });
}
